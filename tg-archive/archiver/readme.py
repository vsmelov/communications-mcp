"""Авто-README для папки одного чата.

Задача: сделать папку чата САМОДОСТАТОЧНОЙ — так, чтобы её можно было отдать
человеку или ИИ-агенту, и он без внешнего контекста понял, что это, какова
структура файлов и JSON, откуда данные и как с ними работать.

README перегенерируется архиватором при каждом save() (обязанность сервиса, не
человека), поэтому статистика в нём всегда актуальна. Править руками бесполезно —
перезапишется.
"""
from __future__ import annotations

from collections import Counter

# (поле, тип, описание). "?" в типе = поле может отсутствовать.
_ROW_FIELDS = [
    ("id", "int", "ID сообщения в Telegram. Первичный ключ строки. По нему докачивают оригинал удалённого медиа."),
    ("ts", "int", "Unix-время отправки (UTC)."),
    ("date_utc", "str", "Читаемое время UTC: `YYYY-MM-DD HH:MM:SS`."),
    ("from", "str", "Отображаемое имя отправителя."),
    ("text", "str", "Текст сообщения. В `dump.json` очищен от секретов; в `dump.unsafe.json` сырой (см. §6)."),
    ("outgoing", "bool?", "`true` — сообщение отправлено владельцем аккаунта."),
    ("reply_to_id", "int?", "ID сообщения, на которое это ответ."),
    ("deleted", "bool?", "`true` — сообщение удалено в Telegram; архив хранит последнюю версию."),
    ("media", "str?", "Вид вложения: `photos`/`voice`/`video_notes`/`videos`/`audio`/`documents`/`stickers`/`gifs`/`webpage`."),
    ("size_bytes", "int?", "Размер вложения в байтах."),
    ("duration_sec", "float?", "Длительность в секундах (voice/video_notes/audio/videos)."),
    ("file", "str?", "Относительный путь к скачанному файлу (`attachments/<вид>/<id>_<имя>`). Отсутствует — файл не хранится (удалён после обработки / пропущен / докачиваемо по id)."),
    ("audio_only", "bool?", "`true` — от видеокружка сохранена только аудиодорожка."),
    ("skipped_reason", "str?", "Почему вложение не скачано (напр. больше лимита)."),
    ("transcript", "str?", "Расшифровка речи (voice/video_notes/audio). В `dump.md` идёт с пометкой `[speech]`."),
    ("transcript_model", "str?", "Чем расшифровано (`telegram` — нативная транскрибация Telegram Premium, бесплатно)."),
    ("audio_dropped", "bool?", "`true` — аудиофайл удалён после расшифровки (текст `transcript` остаётся)."),
    ("description", "str?", "Описание картинки или подробное саммери документа (vision-модель). Секреты уже вырезаны → `[[secret #id ...]]`."),
    ("description_kind", "str?", "`image` / `document`."),
    ("described", "bool?", "`true` — файл описан и удалён; оригинал докачиваем по `id` из Telegram."),
    ("media_secret", "list?", "Типы секретов, найденных И вырезанных из этого медиа (напр. скрин ключа/сид-фразы)."),
]


def _stats(rows: list[dict]) -> dict:
    media = Counter(r["media"] for r in rows if r.get("media"))
    return {
        "messages": len(rows),
        "on_disk": sum(1 for r in rows if r.get("file")),
        "transcripts": sum(1 for r in rows if r.get("transcript")),
        "described": sum(1 for r in rows if r.get("described") or r.get("description")),
        "media_secret": sum(1 for r in rows if r.get("media_secret")),
        "deleted": sum(1 for r in rows if r.get("deleted")),
        "media": media,
    }


def render_readme(chat_name: str, chat_id: int, slug: str, rows: list[dict],
                  meta: dict, archive_state: dict | None = None) -> str:
    s = _stats(rows)
    last_save = (archive_state or {}).get("last_save_utc", "—")
    media_lines = "\n".join(f"| `{k}` | {v} |" for k, v in s["media"].most_common()) or "| — | 0 |"
    field_rows = "\n".join(f"| `{f}` | {t} | {d} |" for f, t, d in _ROW_FIELDS)

    return f"""# Архив чата: {chat_name}

> **Автогенерируемый файл.** Его создаёт и обновляет сервис `tg-archive` при каждой
> синхронизации — не редактируй руками, перезапишется. Назначение README: сделать
> эту папку самодостаточной, чтобы её можно было отдать человеку или ИИ-агенту, и он
> разобрался без внешнего контекста.

## 1. Что это
Полный инкрементальный архив личного Telegram-чата **«{chat_name}»** (chat_id
`{chat_id}`). Снимается через пользовательскую Telethon-сессию (личный аккаунт),
дописывается по мере поступления новых сообщений. Медиа скачивается, речь
расшифровывается, картинки/документы описываются моделью — и всё складывается в
файлы рядом, чтобы отвечать на вопросы по чату чтением с диска, а не постраничными
запросами к Telegram API.

- **Источник:** Telegram (личный аккаунт), сервис `tg-archive`.
- **Период (UTC):** {meta.get('start')} … {meta.get('end')}
- **Сообщений:** {s['messages']}
- **Последнее обновление:** {last_save} UTC

## 2. Файлы в папке
| Файл / папка | Что это |
|---|---|
| `dump.json` | **БЕЗОПАСНАЯ копия:** все сообщения, но секреты вырезаны (`[[secret #id ...]]`). Читай и отправляй наружу ЭТОТ файл. |
| `dump.md` | **БЕЗОПАСНЫЙ** человекочитаемый рендер (речь `[speech]`, 🖼️ описания, 📄 саммери). |
| `dump.unsafe.json` | ⚠️ **СЫРОЙ источник истины:** `text`/`transcript` как в Telegram, МОГУТ СОДЕРЖАТЬ СЕКРЕТЫ. Во внешние API не отправлять. Нужен только когда важен точный оригинал. |
| `manifest.json` | Метаданные архива: покрытие, счётчики, состояние (совместимо с `dump_search` MCP). |
| `attachments/<вид>/` | Скачанные вложения по подпапкам (`photos`, `voice`, …). На файл ссылается поле `file`. |
| `README.md` | Этот файл (автоген). |

Обе версии (`dump.json` и `dump.unsafe.json`) архиватор держит актуальными сам на
каждом save; отличаются только вырезанными секретами.

## 3. Структура `dump.json` / `dump.unsafe.json` (верхний уровень)
```json
{{
  "chat": "<название>",
  "chat_id": {chat_id},
  "meta": {{ "start_ts", "end_ts", "start", "end", "tz":"UTC", "messages", "downloaded", "skipped" }},
  "messages": [ /* массив строк-сообщений, новые сверху; схема в §4 */ ]
}}
```

## 4. Схема строки-сообщения (`messages[]`)
| Поле | Тип | Описание |
|---|---|---|
{field_rows}

## 5. Вложения (`attachments/`)
Файлы лежат по подпапкам вида вложения: `attachments/photos/`, `attachments/voice/`,
`attachments/video_notes/`, `attachments/videos/`, `attachments/audio/`,
`attachments/documents/`, `attachments/stickers/`, `attachments/gifs/`.
Имя файла — `<id>_<оригинальное_имя>`, где `id` = поле `id` строки. Ссылка на файл
лежит в поле `file` (относительный путь от этой папки).

**Важно про «исчезающие» файлы:** после расшифровки аудио и после описания
картинок/документов сам файл удаляется (текст его заменяет), а строка помечается
`audio_dropped`/`described`. Это НЕ потеря данных — оригинал живёт на серверах
Telegram и **докачивается по `id`** (см. §7). Так папка не разрастается.

## 6. Секреты и безопасность
- **`dump.json` и `dump.md` — безопасны.** Секреты (приватные ключи, seed-фразы,
  токены, адреса кошельков) вырезаны и заменены маркером `[[secret #<id> type:<тип>]]`
  (напр. `type:seed_phrase`, `eth_addr`, `api_key_sk`). Поле `media_secret`
  перечисляет, что нашлось в конкретном медиа. **Читай и отправляй наружу именно
  эти файлы.**
- ⚠️ **`dump.unsafe.json` — сырой.** Поля `text`/`transcript` там как в Telegram и
  могут содержать секреты в открытом виде. **Не отправляй его во внешние API.** Он
  нужен только когда требуется точный оригинал текста.

Архиватор держит безопасные копии актуальными автоматически, на каждом save (не
руками). Реестр найденных секретов (соль+хеш+тип+маска — сам секрет НЕ хранится)
лежит в служебной `data/secrets.sqlite3`, вне этой папки намеренно. Разовый прогон
руками при необходимости: `python -m archiver.scrub dump <путь>/dump.unsafe.json`.

## 7. Как с этим работать
- **Отвечать по чату — чтением файлов, не API.** Для обзора/поиска бери `dump.md`
  (или фильтруй `messages[]` в `dump.json` по нужным полям). Это на порядки быстрее
  постраничных запросов к Telegram.
- **Докачать оригинал медиа** (если `described`/`audio_dropped`/нет `file`):
  по `id` через Telegram-MCP (`download_media` / `dump`) — файл вернётся с серверов
  Telegram.
- **Свежесть и догрузка:** `archive_status` — покрытие и прогресс; `archive_refresh`
  с этим `chat_id` — быстро проверить и дотянуть новые сообщения перед ответом.
- **Даты — всегда UTC** (`ts` — unix, `date_utc` — строка UTC). Не полагайся на
  локальные таймзоны.

## 8. Текущая статистика (на {last_save} UTC)
- Сообщений: **{s['messages']}** (удалённых помечено: {s['deleted']})
- Файлов на диске сейчас: {s['on_disk']}
- Расшифровок речи: {s['transcripts']}
- Описаний картинок/документов: {s['described']}
- Сообщений с вырезанным секретом в медиа (`media_secret`): {s['media_secret']}

Вложения по видам (всего встречается в сообщениях):

| Вид | Сообщений |
|---|---|
{media_lines}
"""
